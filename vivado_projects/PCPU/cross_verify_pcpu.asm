    # ========================================
    # 测试1：计算斐波那契数列前10项
    # ========================================
    
    # 初始化（寄存器$8不需要，我们的CPU直接从地址0开始）
    ADDI $1, $0, 0      # fib(0) = 0
    ADDI $2, $0, 1      # fib(1) = 1
    ADDI $3, $0, 10     # 计算10项
    ADDI $4, $0, 0      # 计数器 = 0
    
    # 存储前两项
    STORE $1, 0($0)     # MEM[0] = 0
    STORE $2, 4($0)     # MEM[4] = 1
    ADDI $4, $4, 2      # 计数器 = 2
    
    # 计算剩余8项
fib_loop:
    BZ   $4, $3, fib_done   # if (counter == 10) goto done
    
    ADD  $5, $1, $2         # fib(n) = fib(n-1) + fib(n-2)
    
    # 计算存储地址 = counter * 4
    SLL  $6, $4, 2      # $6 = counter * 4
    STORE $5, 0($6)     # MEM[counter*4] = fib(n)
    
    # 移动到下一项
    ADD  $1, $0, $2     # fib(n-2) = fib(n-1)
    ADD  $2, $0, $5     # fib(n-1) = fib(n)
    ADDI $4, $4, 1      # counter++
    
    JMP  fib_loop

fib_done:
    # ========================================
    # 测试2：计算所有项的和
    # ========================================
    ADDI $10, $0, 0     # sum = 0
    ADDI $11, $0, 0     # index = 0
    ADDI $12, $0, 10    # count = 10
    
sum_loop:
    BZ   $11, $12, sum_done   # if (index == count) goto done
    
    SLL  $13, $11, 2          # offset = index * 4
    LOAD $14, 0($13)    # value = MEM[offset]
    ADD  $10, $10, $14  # sum += value
    ADDI $11, $11, 1    # index++
    
    JMP  sum_loop

sum_done:
    # sum = 88
    STORE $10, 40($0)   # MEM[40] = sum
    
    # ========================================
    # 测试3：算术运算
    # ========================================
    ADDI $20, $0, 100   # $20 = 100
    ADDI $21, $0, 50    # $21 = 50
    ADD  $22, $20, $21  # $22 = 150
    SUB  $23, $20, $21  # $23 = 50
    
    STORE $22, 44($0)   # MEM[44] = 150
    STORE $23, 48($0)   # MEM[48] = 50
    
    # ========================================
    # 测试4：逻辑运算
    # ========================================
    ADDI $24, $0, 255   # $24 = 255
    ADDI $25, $0, 15    # $25 = 15
    AND  $26, $24, $25  # $26 = 15
    OR   $27, $24, $25  # $27 = 255
    XOR  $28, $24, $25  # $28 = 240
    
    STORE $26, 52($0)   # MEM[52] = 15
    STORE $27, 56($0)   # MEM[56] = 255
    STORE $28, 60($0)   # MEM[60] = 240
    
    # ========================================
    # 结束
    # ========================================
    HALT

